#!/usr/bin/env python3
"""Build an atomic release; changed assets get content-hash URLs, unchanged URLs remain.
Usage: python3 tools/build-static-cache.py [--version 3.25.40]
GitHub Actions runs this automatically before publishing. No third-party dependencies.
"""
import argparse,hashlib,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--version');args=parser.parse_args()
version=args.version or json.loads((root/'app-version.json').read_text())['version']
if not re.fullmatch(r'\d+\.\d+\.\d+',version):parser.error('version must be x.y.z')
(root/'app-version.json').write_text(json.dumps({'version':version},indent=2)+'\n')
worker=root/'service-worker.js';previous={}
if worker.exists():
 m=re.search(r'const ASSETS = (\[.*?\]);',worker.read_text(),re.S)
 if m:previous={x['url'].split('?')[0]:x for x in json.loads(m[1])}
def digest(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def update_ref(m):
 filename,old=m.group(1),m.group(2);item=previous.get(filename);sha=digest(root/filename)
 revision=old if item and item['sha256']==sha else sha[:16]
 return filename+'?v='+revision
p=root/'assets/ggfc-sync.js';s=p.read_text();p.write_text(re.sub(r"window.GGFC_VERSION='[^']+'",f"window.GGFC_VERSION='{version}'",s))
p=root/'assets/ggfc-app.js';s=p.read_text();p.write_text(re.sub(r'(assets/ggfc-export\.css)\?v=([\w.-]+)',update_ref,s))
for name in ['index.html','mobile.html']:
 p=root/name;s=p.read_text()
 s=re.sub(r'(assets/[\w.-]+\.(?:js|css))\?v=([\w.-]+)',update_ref,s)
 parts=re.split(r'(<[^>]*>)',s)
 s=''.join(re.sub(r'(?<![\d.])3\.\d+\.\d+(?![\d.])',version,part) if i%2==0 else part for i,part in enumerate(parts))
 p.write_text(s)
urls={}
for name in ['index.html','mobile.html','assets/ggfc-app.js']:
 for m in re.finditer(r'(assets/[\w./-]+\.(?:js|css))\?v=([\w.-]+)',(root/name).read_text()):urls[m[1]]=m[0]
for folder in ['assets','icons']:
 for p in sorted((root/folder).rglob('*')):
  if p.suffix in ['.js','.css','.svg','.woff','.png']:urls.setdefault(p.relative_to(root).as_posix(),p.relative_to(root).as_posix())
for name in ['index.html','mobile.html','offline.html','manifest.webmanifest','app-version.json']:urls[name]=name
assets=[{'url':url,'sha256':digest(root/name)} for name,url in sorted(urls.items())]
body=(root/'tools/service-worker.template.js').read_text()
fingerprint=hashlib.sha256((json.dumps(assets)+body).encode()).hexdigest()[:16]
worker.write_text('/* Generated by tools/build-static-cache.py; do not edit by hand. */\nconst RELEASE = '+json.dumps(version+'-'+fingerprint)+';\nconst ASSETS = '+json.dumps(assets,indent=2)+';\n'+body)
print(f'Generated {worker.name}: {len(assets)} verified static assets; release {version}-{fingerprint}')
